import matplotlib.pyplot as plt
import numpy as np
import matplotlib.dates as mdates

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

x = np.linspace(0, L, 500)
V = np.zeros_like(x)


for i in range(len(x)):
    if x[i] < 2:
        V[i] = R_A - (q_1 * x[i])
    elif x[i] < 4:
        V[i] = R_A - (q_1 * 2) - P_1
    else:
        V[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (x[i] - 4))

plt.figure(figsize = (10, 4))
plt.plot(x, V, color = 'darkgreen')
plt.fill_between(x, V, 0, color = 'limegreen', alpha = 0.3)   # filled area under curve
plt.title('Shear Diagram')
plt.xlabel('x ft')
plt.ylabel('V lbs')
plt.xlim(0, L)
plt.grid(True)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

x = np.linspace(0, L, 500)
M = np.zeros_like(x)


for i in range(len(x)):
    if x[i] < 2:
        M[i] = (R_A * x[i]) - (q_1 * x[i]**2 / 2)
    elif x[i] < 4:
        M[i] = (R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2))
    else:
        M[i] = ((R_A * x[i]) - (q_1 * 2 * (x[i] - 1)) - (P_1 * (x[i] - 2)) + (R_B * (x[i] - 4)) - (q_2 * (x[i] - 4) * ((x[i] - 4) / 2)))

plt.figure(figsize=(10, 4))
plt.plot(x, M, color='darkblue')
plt.fill_between(x, M, 0, color='blue', alpha=0.3)
plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.xlim(0, L)
plt.grid(True)
plt.show()

