"""### Part 5 - Average U.S. Daily Birth Data

You will now create a graph using average daily birth data in the U.S.

### Numpy Array Creation & Slicing

Slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on the HW instructions page:

*   x - Date
*   y_1 - Births
"""

with open('/content/2012-US-Birth-Rates.csv', 'r') as file:
    next(file)
    data = []
    for line in file:
        line_data = line.strip().split(',')
        line_data[0] = line_data[0].strip('"')
        line_data[1] = float(line_data[1])
        data.append(line_data)

x = np.array([line[0] for line in data], dtype='datetime64[D]')
y_1 = np.array([line[1] for line in data])

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below.
"""

plt.figure(figsize=(12, 4))
plt.plot(x, y_1, color='tab:blue')
plt.title('Average U.S. Daily Births (2012)')
plt.xlabel('Date')
plt.ylabel('Average Daily Births')
plt.ylim(3700, 5400)    # leave room for the holiday labels
plt.grid(True)

holidays = [
    ("New Year's Day",   '2012-01-01', '2012-02-10', 4200),
    ('Independence Day', '2012-07-04', '2012-05-20', 4300),
    ('Thanksgiving',     '2012-11-22', '2012-10-01', 4300),
    ('Christmas',        '2012-12-25', '2012-10-25', 3900),
]
for label, date, text_date, text_y in holidays:
    d = np.datetime64(date)
    y_val = y_1[x == d][0]    # births on that day
    plt.annotate(label,
                 xy=(d, y_val),
                 xytext=(np.datetime64(text_date), text_y),
                 arrowprops=dict(arrowstyle='->', color='black',
                                 connectionstyle='arc3,rad=0.3'),
                 ha='center')
plt.show()